from typing import List, Tuple

def get_stock_pool() -> List[Tuple[str, str, str]]:
    """
    返回: [(code, name_placeholder, market), ...]
    name 暂时用代码替代，后续从API补充
    """
    pool = []
    seen = set()

    def add(code: str, market: str):
        if code not in seen and len(code) == 6 and code.isdigit():
            seen.add(code)
            pool.append((code, code, market))

    # ==================== 沪市主板 (sh) ====================
    # 600000 - 600999 金融/大型工业
    for i in range(600000, 601000):
        add(str(i), "sh")

    # 601000 - 601999 央企/大盘
    for i in range(601000, 602000):
        add(str(i), "sh")

    # 603000 - 603999 次新股/民营
    for i in range(603000, 604000):
        add(str(i), "sh")

    # 605000 - 605999 次新股
    for i in range(605000, 606000):
        add(str(i), "sh")

    # 688000 - 688999 科创板
    for i in range(688000, 689000):
        add(str(i), "sh")

    # ==================== 深市主板 (sz) ====================
    # 000001 - 000999 金融/大型
    for i in range(1, 1000):
        add(f"000{i:03d}", "sz")

    # 001000 - 001999 地方国企
    for i in range(1, 1000):
        add(f"001{i:03d}", "sz")

    # ==================== 中小板的 (sz) ====================
    # 002000 - 002999 中小板/民营
    for i in range(2000, 3000):
        add(str(i), "sz")

    # ==================== 创业板 (sz) ====================
    # 300000 - 300999 创业板
    for i in range(300000, 301000):
        add(str(i), "sz")

    # ==================== 北交所 (bj) ====================
    # 830000 - 899999 北交所
    for i in range(830000, 832000):
        add(str(i), "bj")
    for i in range(870000, 872000):
        add(str(i), "bj")

    # 920000 - 929999 北交所
    for i in range(920000, 930000):
        add(str(i), "bj")

    return pool


