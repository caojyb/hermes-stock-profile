# -*- coding: utf-8 -*-
"""
交易所法定节假日表（2026-09-18 二轮审计 P1-4 修复）
==================================================
此前 trading_calendar 只按 weekday<5 判断，法定假日（工作日休市）会被
误判为交易日，9-25 中秋这类假期会触发无数据扫描/虚假 DATA_NOT_READY 告警。

节假日来源：国务院办公厅放假安排 + 交易所休市公告。
- 已由上交所指数 K 线实证核对：2026 春节 2/16-2/23、元旦 1/1-1/2
- 未来假日按官方公告手工维护；每年 11-12 月核对次年安排
- 兜底逻辑不变：工作日但无 K 线 → DATA_NOT_READY，不会因日历缺失产生虚假信号
"""
from __future__ import annotations

from datetime import date

# 交易所休市的法定节假日（工作日部分；周末本就休市不列）
# 格式: {年份: [ISO 日期, ...]}
EXCHANGE_HOLIDAYS: dict[int, set[str]] = {
    2026: {
        # 元旦: 1/1(四) 1/2(五)
        '2026-01-01', '2026-01-02',
        # 春节: 2/16(一) ~ 2/23(一)（除夕 2/16，官方假期+调休后交易所休 6 个工作日，已用指数 K 线实证）
        '2026-02-16', '2026-02-17', '2026-02-18', '2026-02-19', '2026-02-20', '2026-02-23',
        # 清明: 4/6(一)（4/4 清明节，4/4-4/6 连休）
        '2026-04-06',
        # 劳动节: 5/1(五) ~ 5/5(二)（含调休工作日顺延，交易所休 5/1、5/4、5/5 三个工作日）
        '2026-05-01', '2026-05-04', '2026-05-05',
        # 端午: 6/19(五)（6/19 端午节）
        '2026-06-19',
        # 中秋: 9/25(五)（9/25 中秋节，与周末连休）
        '2026-09-25',
        # 国庆: 10/1(四) ~ 10/8(四)（含调休，交易所休 10/1、10/2、10/5、10/6、10/7、10/8 共 6 个工作日；
        #       10/9(五)、10/10(六) 具体以官方公告为准，10/10 若为调休上班日交易所仍休市）
        '2026-10-01', '2026-10-02', '2026-10-05', '2026-10-06', '2026-10-07', '2026-10-08', '2026-10-09',
    },
}


def is_holiday(d: date) -> bool:
    """法定节假日（工作日休市日）= True。"""
    return d.isoformat() in EXCHANGE_HOLIDAYS.get(d.year, set())


def is_trading_calendar_day(d: date | None = None) -> bool:
    """日历交易日 = 周一至周五 且 非法定节假日。"""
    d = d or date.today()
    return d.weekday() < 5 and not is_holiday(d)
